#!/usr/bin/env python3
"""Generate the Unicode 17.0.0 grapheme-cluster table of shosai-quote-v1.

The quote normalization profile `shosai-quote-v1` (RFD 16, PHASE-0) pins
Unicode 17.0.0 data for extended grapheme clusters. No Dart package on pub.dev
segments by Unicode 17 (`characters` 1.4.1, which the Flutter SDK pins,
implements Unicode 16), so the Dart core carries its own UAX #29 segmenter and
this script transcribes the data it needs from the Unicode Character Database:

- `Grapheme_Cluster_Break` from `auxiliary/GraphemeBreakProperty.txt`,
- `Extended_Pictographic` from `emoji/emoji-data.txt`,
- `Indic_Conjunct_Break` from `DerivedCoreProperties.txt`.

It also copies `auxiliary/GraphemeBreakTest.txt`, the conformance vectors the
segmenter is tested against.

Usage:

    scripts/generate-quote-unicode-tables.py            # download and write
    scripts/generate-quote-unicode-tables.py --ucd DIR  # use local UCD files
    scripts/generate-quote-unicode-tables.py --check    # fail if outputs differ
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
import urllib.request
from pathlib import Path

UNICODE_VERSION = "17.0.0"
BASE_URL = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd"
FILES = {
    "GraphemeBreakProperty.txt": "auxiliary/GraphemeBreakProperty.txt",
    "GraphemeBreakTest.txt": "auxiliary/GraphemeBreakTest.txt",
    "emoji-data.txt": "emoji/emoji-data.txt",
    "DerivedCoreProperties.txt": "DerivedCoreProperties.txt",
}

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "packages" / "shosai_core"
TABLE = PACKAGE / "lib" / "src" / "annotations" / "grapheme_table.dart"
CONFORMANCE = PACKAGE / "test" / "fixtures" / "GraphemeBreakTest-17.0.0.txt"

# Must match the constants in lib/src/annotations/graphemes.dart.
GCB = {
    "Other": 0,
    "CR": 1,
    "LF": 2,
    "Control": 3,
    "Extend": 4,
    "ZWJ": 5,
    "Regional_Indicator": 6,
    "Prepend": 7,
    "SpacingMark": 8,
    "L": 9,
    "V": 10,
    "T": 11,
    "LV": 12,
    "LVT": 13,
}
EXT_PICT = 1 << 4
INCB = {"Linker": 1 << 5, "Consonant": 2 << 5, "Extend": 3 << 5}

LINE = re.compile(
    r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z_]+)"
    r"(?:\s*;\s*([A-Za-z_]+))?"
)


def ranges(path: Path):
    for line in path.read_text(encoding="utf-8").splitlines():
        match = LINE.match(line)
        if match:
            start = int(match.group(1), 16)
            end = int(match.group(2) or match.group(1), 16)
            yield start, end, match.group(3), match.group(4)


def check_version(path: Path) -> None:
    header = path.read_text(encoding="utf-8").splitlines()[:12]
    major_minor = UNICODE_VERSION.rsplit(".", 1)[0]
    if not (
        f"-{UNICODE_VERSION}.txt" in header[0]
        or f"# Version: {major_minor}" in header
    ):
        sys.exit(f"{path.name} is not Unicode {UNICODE_VERSION}: {header[0]}")


def build_table(ucd: Path) -> str:
    values = bytearray(0x110000)
    for start, end, name, _ in ranges(ucd / "GraphemeBreakProperty.txt"):
        for scalar in range(start, end + 1):
            values[scalar] |= GCB[name]
    for start, end, name, _ in ranges(ucd / "emoji-data.txt"):
        if name == "Extended_Pictographic":
            for scalar in range(start, end + 1):
                values[scalar] |= EXT_PICT
    for start, end, name, value in ranges(ucd / "DerivedCoreProperties.txt"):
        if name == "InCB":
            for scalar in range(start, end + 1):
                values[scalar] |= INCB[value]

    starts: list[int] = []
    kinds: list[int] = []
    for scalar, value in enumerate(values):
        if not kinds or kinds[-1] != value:
            starts.append(scalar)
            kinds.append(value)

    def rows(numbers: list[int], width: int) -> str:
        cells = [f"0x{number:0{width}x}," for number in numbers]
        return "\n".join(
            "  " + " ".join(cells[index : index + 8])
            for index in range(0, len(cells), 8)
        )

    return f"""// GENERATED by scripts/generate-quote-unicode-tables.py from the Unicode
// {UNICODE_VERSION} Character Database. Do not edit.
// dart format off
//
// Each range starting at [graphemeRangeStarts][i] holds the properties
// [graphemeRangeValues][i]: bits 0-3 Grapheme_Cluster_Break, bit 4
// Extended_Pictographic, bits 5-6 Indic_Conjunct_Break.

/// The Unicode version of these tables.
const graphemeTableUnicodeVersion = '{UNICODE_VERSION}';

const graphemeRangeStarts = <int>[
{rows(starts, 6)}
];

const graphemeRangeValues = <int>[
{rows(kinds, 2)}
];
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd", type=Path, help="directory holding the UCD files")
    parser.add_argument("--check", action="store_true", help="verify, do not write")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as temporary:
        ucd = args.ucd or Path(temporary)
        if args.ucd is None:
            for name, remote in FILES.items():
                urllib.request.urlretrieve(f"{BASE_URL}/{remote}", ucd / name)
        for name in FILES:
            check_version(ucd / name)
        outputs = {
            TABLE: build_table(ucd),
            CONFORMANCE: (ucd / "GraphemeBreakTest.txt").read_text(encoding="utf-8"),
        }

    stale = [path for path, text in outputs.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date", file=sys.stderr)
        sys.exit(1 if stale else 0)
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
