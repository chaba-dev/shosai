/// Interactive entry point for the Phase C EPUB evaluation prototype.
///
/// Run with:
///   flutter run -d linux -t lib/main.dart
library;

import 'dart:io';

import 'package:flutter/material.dart';

import 'fixtures.dart';
import 'reader/controller.dart';
import 'reader/effects.dart';
import 'reader/message.dart';
import 'reader/script_fonts.dart';
import 'reader/view.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  // The prototype loads the shared Inter/Noto Sans JP binaries from the
  // repository instead of bundling copies here.
  await loadBundledContentFonts();
  // Prototype-only: register host faces for scripts the bundled fonts do not
  // cover so bidi layout can be inspected. Production must bundle them.
  final fallbacks = await loadScriptFallbackFamilies();
  runApp(EpubEvalApp(contentFallbackFamilies: fallbacks));
}

class EpubEvalApp extends StatefulWidget {
  const EpubEvalApp({super.key, this.contentFallbackFamilies = const []});

  final List<String> contentFallbackFamilies;

  @override
  State<EpubEvalApp> createState() => _EpubEvalAppState();
}

class _EpubEvalAppState extends State<EpubEvalApp> {
  EpubReaderController? _controller;

  void _open(String path) {
    _controller?.dispose();
    // Prototype persistence: a JSON position file per document, not SQLite.
    // The directory is regenerated review data (gitignored).
    final storeDirectory = Directory('artifacts/positions');
    final controller = EpubReaderController(
      contentFallbackFamilies: widget.contentFallbackFamilies,
      positionStore: EpubFilePositionStore(storeDirectory),
    );
    controller.dispatch(EpubReaderOpenRequested(path));
    setState(() => _controller = controller);
  }

  @override
  void dispose() {
    _controller?.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final controller = _controller;
    return MaterialApp(
      title: 'Shōsai EPUB evaluation prototype',
      debugShowCheckedModeBanner: false,
      home: controller == null
          ? _FixturePicker(onOpen: _open)
          : ListenableBuilder(
              listenable: controller,
              builder: (context, _) => EpubReaderView(
                controller: controller,
                model: controller.model,
              ),
            ),
    );
  }
}

class _FixturePicker extends StatelessWidget {
  const _FixturePicker({required this.onOpen});

  final void Function(String path) onOpen;

  @override
  Widget build(BuildContext context) {
    final fixtures = prototypeFixtures();
    return Scaffold(
      appBar: AppBar(title: const Text('Shōsai EPUB evaluation prototype')),
      body: ListView(
        children: [
          const Padding(
            padding: EdgeInsets.all(16),
            child: Text(
              'Evaluation prototype: Dart-owned EPUB parsing/normalization '
              'with Flutter layout. Not a production engine.\n\n'
              'Fixtures are generated by tool/generate_fixtures.py; '
              'conformance fixtures come from the repository.',
            ),
          ),
          for (final fixture in fixtures)
            ListTile(
              title: Text(fixture.name),
              subtitle: Text(fixture.path),
              onTap: () => onOpen(fixture.path),
            ),
        ],
      ),
    );
  }
}
