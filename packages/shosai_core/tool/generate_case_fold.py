#!/usr/bin/env python3
"""Generate lib/src/search/case_fold_table.dart from Python's str.casefold.

str.casefold applies Unicode full case folding (CaseFolding.txt statuses C
and F), the folding in-document search uses. Run from the package root:

    python3 tool/generate_case_fold.py
"""

import sys
import unicodedata
from pathlib import Path

simple = []
full = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    folded = chr(cp).casefold()
    if folded == chr(cp):
        continue
    if len(folded) == 1:
        simple.append((cp, ord(folded)))
    else:
        full.append((cp, [ord(c) for c in folded]))


def rows(items, per_line):
    for i in range(0, len(items), per_line):
        yield "  " + " ".join(items[i : i + per_line])


simple_items = [f"0x{cp:X}, 0x{to:X}," for cp, to in simple]
full_items = [
    f"0x{cp:X}: [{', '.join(f'0x{c:X}' for c in to)}]," for cp, to in full
]
out = [
    f"// Generated by tool/generate_case_fold.py from Unicode "
    f"{unicodedata.unidata_version}. Do not edit.",
    "",
    "part of 'case_fold.dart';",
    "",
    f"const _unicodeVersion = '{unicodedata.unidata_version}';",
    "",
    "/// Code points that fold to one other code point, ascending, each followed",
    "/// by its folding.",
    "// dart format off",
    "const _simpleFolds = <int>[",
    *rows(simple_items, 6),
    "];",
    "",
    "/// Code points that fold to several code points.",
    "const _fullFolds = <int, List<int>>{",
    *rows(full_items, 3),
    "};",
    "// dart format on",
    "",
]
target = Path(sys.argv[1] if len(sys.argv) > 1 else "lib/src/search/case_fold_table.dart")
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(out))
print(f"{target}: {len(simple)} simple and {len(full)} full foldings")
